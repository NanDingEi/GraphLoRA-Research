#!/usr/bin/env python3
"""CPU-only check: rank mapping, same P budget, small head, and actual gradients."""
import os
import sys
from contextlib import contextmanager
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from experiments.no31_cora_original.adapter import OriginalCoRARuntime
from experiments.no31_cora_original.weight_generator import PerceptualWeightsGenerator

RANKS = (12, 14, 18, 20)


@contextmanager
def env_override(values):
    previous = {key: os.environ.get(key) for key in values}
    try:
        os.environ.update({key: str(value) for key, value in values.items()})
        yield
    finally:
        for key, value in previous.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def main():
    with env_override({
        "NO31_CORA_ALPHA": "48",
        "NO31_CORA_PROJECTIONS": "q_proj,k_proj,v_proj,o_proj",
        "NO31_CORA_LAYERS": "0-31",
        "NO31_CORA_INPUT": "concat",
        "NO31_CORA_INJECTION_MODE": "shared",
        "NO31_CORA_RANK_PROFILE": "12-14-18-20",
            "NO31_CORA_GROUP_PROJECTORS": "off",
        "NO31_CORA_RESIDUAL_RATIO": "0",
        "NO31_CORA_DEPTH_PROFILE": "uniform",
        "NO31_CORA_PROJECTION_SCALES": "q_proj=1,k_proj=1,v_proj=1,o_proj=1",
    }):
        runtime = OriginalCoRARuntime()

    assert runtime.rank_profile == RANKS
    assert runtime.rank_for_layer(0) == runtime.rank_for_layer(7) == 12
    assert runtime.rank_for_layer(8) == runtime.rank_for_layer(15) == 14
    assert runtime.rank_for_layer(16) == runtime.rank_for_layer(23) == 18
    assert runtime.rank_for_layer(24) == runtime.rank_for_layer(31) == 20
    assert runtime.scaling == 3.0
    assert runtime.expected_targets == 128

    p_base = 32 * 4 * 4096 * 16
    p_new = sum(8 * 4 * 4096 * rank for rank in RANKS)
    assert p_base == p_new == 8_388_608, (p_base, p_new)

    # Small reduced-dimension generator; final head is EXACTLY the original
    # rank-16 head initialized with the same seed and common QFormer.
    kwargs = dict(num_queries=4, user_embedding_size=16, hidden_size=32,
                  r=16, input_mode="concat", injection_mode="shared")
    torch.manual_seed(123456)
    base = PerceptualWeightsGenerator(**kwargs)
    base_rng = torch.get_rng_state().clone()
    torch.manual_seed(123456)
    grouped = PerceptualWeightsGenerator(
        **kwargs, rank_profile=RANKS
    )
    grouped_rng = torch.get_rng_state().clone()
    assert torch.equal(base.final.weight, grouped.final.weight)
    assert torch.equal(base.final.bias, grouped.final.bias)
    assert torch.equal(base_rng, grouped_rng), (
        "The compact extension head must not consume the G2 RNG stream"
    )
    assert grouped.final.weight.shape == (32 * 16, 32)
    assert grouped.extra_rank_head[0].weight.shape == (32, 32)
    assert grouped.extra_rank_head[2].weight.shape == (32 * 4, 32)

    extra = sum(p.numel() for p in grouped.extra_rank_head.parameters())
    expected_extra_small = (32 * 32 + 32) + (32 * (32 * 4) + 32 * 4)
    assert extra == expected_extra_small
    # Full-sized CoRA (MF256, LLM4096) adds exactly this many parameters:
    full_extra = (512 * 32 + 32) + (32 * 4096 * 4 + 4096 * 4)
    assert full_extra == 557_088
    full_main_head = 512 * (4096 * 16) + (4096 * 16)
    overhead = full_extra / (p_base + full_main_head)
    assert overhead < 0.02, overhead

    features = torch.randn(3, 32)
    weights = grouped(features)
    assert set(weights.keys()) == set(RANKS)
    for rank in RANKS:
        w = weights[rank]
        assert w.shape == (3, 32, rank), (rank, w.shape)
        assert torch.isfinite(w).all(), rank
        assert torch.allclose(w.flatten(1).norm(dim=-1), torch.ones(3),
                              atol=1e-5), rank

    # Across ranks, selected prefix channels must be reused before
    # normalizing each group, not generated by four unrelated heads.
    for small, big in zip(RANKS[:-1], RANKS[1:]):
        a = weights[small]
        b = weights[big][..., :small]
        a_unit = torch.nn.functional.normalize(a.flatten(1), dim=-1)
        b_unit = torch.nn.functional.normalize(b.flatten(1), dim=-1)
        assert torch.allclose(a_unit, b_unit, atol=1e-5)

    # Backward through the rank >16 channels must reach the new branch,
    # while all groups must still train the G2-compatible first-16 head.
    loss = sum(
        (w * torch.randn_like(w)).sum()
        for w in weights.values()
    )
    loss.backward()
    base_grad = grouped.final.weight.grad
    extra_grad = grouped.extra_rank_head[2].weight.grad
    assert base_grad is not None and torch.isfinite(base_grad).all()
    assert extra_grad is not None and torch.isfinite(extra_grad).all()
    assert base_grad.abs().sum().item() > 0
    assert extra_grad.abs().sum().item() > 0

    print(
        "[NIGHT14-CPU-PASS] ranks=12/14/18/20; P=8,388,608 exactly G2; "
        "head=rank16 unchanged; new head=557,088 params; "
        f"relative_extra={100*overhead:.3f}%; "
        "RNG parity, shared channel prefixes and backward gradients verified",
        flush=True,
    )


if __name__ == "__main__":
    main()
